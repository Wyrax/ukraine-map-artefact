#!/usr/bin/env node
// Generates the synthetic showcase dataset (deterministic). Run: node artefacts/showcase/make-data.mjs
// The numbers are invented and the page labels them as demo data.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REGIONS } from '../../src/map/catalog.js';

const here = path.dirname(fileURLToPath(import.meta.url));
let seed = 20261124;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296);

// rough relative weights (bigger cities → more users)
const weight = {
  'UA-30': 9, 'UA-46': 4.2, 'UA-12': 4.6, 'UA-63': 3.9, 'UA-51': 3.6, 'UA-32': 2.8, 'UA-05': 2.1, 'UA-71': 1.6,
  'UA-18': 1.6, 'UA-53': 1.9, 'UA-56': 1.4, 'UA-07': 1.3, 'UA-61': 1.3, 'UA-68': 1.6, 'UA-26': 1.7, 'UA-21': 1.6,
  'UA-77': 1.1, 'UA-35': 1.2, 'UA-48': 1.4, 'UA-65': 1.0, 'UA-23': 2.0, 'UA-14': 1.5, 'UA-09': 1.15, 'UA-59': 1.3,
  'UA-74': 1.2, 'UA-43': 1.2,
};
const ENVS = [
  { id: 'dev', label: { uk: 'Розробка', en: 'Development' }, share: 0.08 },
  { id: 'test', label: { uk: 'Тестування', en: 'Testing' }, share: 0.14 },
  { id: 'stage', label: { uk: 'Передпрод', en: 'Staging' }, share: 0.1 },
  { id: 'prod', label: { uk: 'Продакшн', en: 'Production' }, share: 0.68 },
];
const UK_M = ['січ', 'лют', 'бер', 'кві', 'тра', 'чер', 'лип', 'сер', 'вер', 'жов', 'лис', 'гру'];
const EN_M = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

const periods = [];
const periodLabels = {};
for (let y = 2025, m = 0; y < 2026 || m < 10; ) {
  const id = `${y}-${String(m + 1).padStart(2, '0')}`;
  periods.push(id);
  periodLabels[id] = { uk: `${UK_M[m]} ${y}`, en: `${EN_M[m]} ${y}` };
  if (++m === 12) {
    m = 0;
    y++;
  }
}

const values = [];
const regionBias = Object.fromEntries(REGIONS.map((r) => [r.id, { growth: 0.015 + rnd() * 0.035, prodTilt: (rnd() - 0.5) * 0.25, start: periods.length * rnd() * 0.25 }]));
// Kyiv and Crimea have data from the first month
for (const id of ['UA-30', 'UA-43']) regionBias[id].start = 0;
for (const r of REGIONS) {
  const w = weight[r.id];
  if (!w) continue; // no data for this region
  const b = regionBias[r.id];
  periods.forEach((p, i) => {
    if (i < b.start) return; // some regions join later
    const base = w * 420 * Math.pow(1 + b.growth, i) * (0.92 + rnd() * 0.16);
    for (const e of ENVS) {
      let share = e.share;
      if (e.id === 'prod') share = Math.max(0.35, Math.min(0.85, share + b.prodTilt + i * 0.004));
      else share = share * (1 - (b.prodTilt + i * 0.004) * 0.9);
      values.push([r.id, e.id, p, Math.round(base * share)]);
    }
  });
}
// Sevastopol: the same monthly total as Crimea (so the city circle never stands out from the peninsula on the
// choropleth), with ~5 % of production users moved to testing so the two are not identical
for (const [, env, p, v] of values.filter((row) => row[0] === 'UA-43')) {
  const shift = Math.round(values.find((row) => row[0] === 'UA-43' && row[1] === 'prod' && row[2] === p)[3] * 0.05);
  values.push(['UA-40', env, p, env === 'prod' ? v - shift : env === 'test' ? v + shift : v]);
}

// region → region moves (demo): mostly towards Kyiv and Lviv, plus neighbours
const flows = [];
const pairs = [
  ['UA-14', 'UA-12'], ['UA-09', 'UA-63'], ['UA-63', 'UA-30'], ['UA-12', 'UA-30'], ['UA-51', 'UA-30'], ['UA-23', 'UA-12'],
  ['UA-65', 'UA-51'], ['UA-48', 'UA-51'], ['UA-59', 'UA-30'], ['UA-74', 'UA-30'], ['UA-30', 'UA-46'], ['UA-14', 'UA-46'],
  ['UA-63', 'UA-46'], ['UA-05', 'UA-30'], ['UA-18', 'UA-30'], ['UA-12', 'UA-26'], ['UA-46', 'UA-21'], ['UA-30', 'UA-32'],
];
periods.forEach((p, i) => {
  for (const [a, b] of pairs) {
    const v = Math.round((40 + rnd() * 160) * (1 + Math.sin(i / 3 + a.length) * 0.35));
    flows.push([a, b, p, v]);
  }
});

const data = {
  meta: {
    title: { uk: 'Користувачі за регіонами (демо)', en: 'Users by region (demo)' },
    unit: { uk: 'корист.', en: 'users' },
    source: { uk: 'Синтетичні демо-дані, згенеровані make-data.mjs', en: 'Synthetic demo data generated by make-data.mjs' },
    updated: '2026-11-24',
  },
  series: ENVS.map(({ id, label }) => ({ id, label })),
  periods,
  periodLabels,
  values: { columns: ['region', 'series', 'period', 'value'], rows: values },
  flows: { columns: ['from', 'to', 'period', 'value'], rows: flows },
};
fs.writeFileSync(path.join(here, 'data.json'), JSON.stringify(data));
console.log(`showcase data: ${values.length} values, ${flows.length} flows, ${periods.length} periods`);
