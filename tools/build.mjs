#!/usr/bin/env node
// Builds artefacts/<slug>/ (artefact.json + data.json) into one self-contained dist/<slug>.html.
//
//   node tools/build.mjs <slug>                 build once
//   node tools/build.mjs --all                  build every artefact
//   node tools/build.mjs <slug> --watch --serve rebuild on change into dist/dev/ + serve it with live reload (port 5173)
//   Publish only dist/<slug>.html (production build), never dist/dev/.
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = (...a) => path.join(ROOT, ...a);
const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const opt = (f, d) => (args.includes(f) ? args[args.indexOf(f) + 1] : d);

export const LAYERS = ['choropleth', 'bubbles', 'bars', 'stacked', 'pies', 'radial', 'radar', 'flows'];
export const PANELS = ['ranking', 'timeline-chart', 'heatmap', 'sankey', 'radar'];

const readJSON = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const pick = (v, lang = 'uk') => (v && typeof v === 'object' ? v[lang] ?? v.uk ?? v.en ?? '' : v ?? '');
const escHtml = (v) => String(v).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const jsonForScript = (o) => JSON.stringify(o).replace(/</g, '\\u003c');

// ---------- colour presets (src/lib/styles/palettes.json, generated by tools/make-palettes.mjs) ----------
const OCC = { light: '#b4383a', dark: '#e66767' };
/** CSS tokens for the default preset on :root, plus every other preset under :root[data-palette] when the picker is on. */
function paletteCss(pal, def, withPicker) {
  const vars = (m, mode) =>
    [
      ...m.seq.map((c, i) => `--seq-${i + 1}:${c}`),
      ...m.seqOn.map((c, i) => `--seq-on-${i + 1}:${c}`),
      ...m.cat.map((c, i) => `--c${i + 1}:${c}`),
      `--accent:${m.accent}`,
      `--sel:${m.sel}`,
      `--occ:${m.occ || OCC[mode]}`,
      `--occ-line:${m.occ || OCC[mode]}`,
    ].join(';');
  let css = '/* colour preset tokens, generated by tools/build.mjs */\n';
  for (const p of pal.presets.filter((x) => withPicker || x.id === def)) {
    const at = p.id === def ? '' : `[data-palette='${p.id}']`;
    css += `:root${at}{${vars(p.light, 'light')}}\n`;
    css += `@media (prefers-color-scheme: dark){:root${at}:not([data-theme='light']){${vars(p.dark, 'dark')}}}\n`;
    css += `:root[data-theme='dark']${at}{${vars(p.dark, 'dark')}}\n`;
  }
  return css;
}

/** Checks config ↔ data consistency in Node before bundling. Returns warnings; throws on hard errors. */
async function validate(slug, config, data) {
  const { prepareData, buildMeasures } = await import(pathToFileURL(P('src/lib/core/data.js')).href + `?t=${Date.now()}`);
  const prepared = prepareData(data, config);
  const measures = buildMeasures(prepared, config);
  const warnings = [];
  if (prepared.unmatched.length) warnings.push(`unmatched region names: ${prepared.unmatched.join(', ')}`);
  const need = (id, where) => {
    if (id != null && !measures.has(id)) throw new Error(`[${slug}] ${where}: unknown series/measure "${id}". Known: ${[...measures.keys()].join(', ')}`);
  };
  for (const m of config.modes || []) {
    for (const l of m.layers || []) {
      if (!LAYERS.includes(l.type)) throw new Error(`[${slug}] mode "${m.id}": unknown layer type "${l.type}". Known: ${LAYERS.join(', ')}`);
      need(l.value, `mode "${m.id}" ${l.type}.value`);
      for (const s of [].concat(l.series || [])) need(s, `mode "${m.id}" ${l.type}.series`);
      if (typeof l.max === 'string' && l.max !== 'domain') need(l.max, `mode "${m.id}" ${l.type}.max`);
    }
  }
  for (const p of config.panels || []) {
    if (!PANELS.includes(p.type)) throw new Error(`[${slug}] unknown panel type "${p.type}". Known: ${PANELS.join(', ')}`);
    need(p.value, `panel ${p.type}.value`);
    for (const s of [].concat(p.series || [])) need(s, `panel ${p.type}.series`);
  }
  const regionsWithData = new Set(prepared.regionIds.filter((r) => prepared.periods.some((_, i) => prepared.has(r, i))));
  if (regionsWithData.size < 27) warnings.push(`regions without any data: ${prepared.regionIds.filter((r) => !regionsWithData.has(r)).join(', ')}`);
  return { warnings, prepared };
}

export async function build(slug, { dev = false } = {}) {
  const dir = P('artefacts', slug);
  const config = readJSON(path.join(dir, 'artefact.json'));
  const data = readJSON(path.join(dir, 'data.json'));
  const regions = readJSON(P('src/map/regions.json'));
  // latest occupation snapshot (tools/occupation.mjs), drawn as an optional overlay
  const occFile = P('src/map/occupation.json');
  if (fs.existsSync(occFile)) {
    const { asOf, labelYear, source, area, line } = readJSON(occFile);
    regions.occupation = { asOf, labelYear, source, area, line };
  }
  const { warnings, prepared } = await validate(slug, config, data);

  const layerTypes = [...new Set((config.modes || [{ layers: [{ type: 'choropleth' }] }]).flatMap((m) => (m.layers || []).map((l) => l.type)))];
  if (!config.modes?.length) layerTypes.push('choropleth');
  const panelTypes = [...new Set((config.panels || []).map((p) => p.type))];
  const imp = (p) => JSON.stringify(p.replace(/\\/g, '/'));
  const ident = (t) => t.replace(/[^a-z0-9]/gi, '_');
  const entry = [
    `import { boot } from ${imp(P('src/lib/app.js'))};`,
    ...layerTypes.map((t) => `import L_${ident(t)} from ${imp(P('src/lib/layers', t + '.js'))};`),
    ...panelTypes.map((t) => `import P_${ident(t)} from ${imp(P('src/lib/panels', t + '.js'))};`),
    `boot({ layers: { ${layerTypes.map((t) => `${JSON.stringify(t)}: L_${ident(t)}`).join(', ')} }, panels: { ${panelTypes.map((t) => `${JSON.stringify(t)}: P_${ident(t)}`).join(', ')} } });`,
  ].join('\n');
  fs.mkdirSync(P('.tmp'), { recursive: true });
  const entryFile = P('.tmp', `entry-${slug}.js`);
  fs.writeFileSync(entryFile, entry);

  const res = await esbuild.build({
    entryPoints: [entryFile],
    bundle: true,
    format: 'iife',
    minify: !dev,
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  const js = res.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const pal = readJSON(P('src/lib/styles/palettes.json'));
  const palId = config.options?.palette || pal.default;
  if (!pal.presets.some((p) => p.id === palId)) throw new Error(`[${slug}] unknown options.palette "${palId}". Known: ${pal.presets.map((p) => p.id).join(', ')}`);
  const picker = !!config.options?.palettePicker;
  const css = fs.readFileSync(P('src/lib/styles/base.css'), 'utf8') + '\n' + paletteCss(pal, palId, picker);
  // the picker needs the names and swatches of every preset
  const pageConfig = picker
    ? { ...config, palettes: pal.presets.map(({ id, name, light, dark }) => ({ id, name, light: { seq: light.seq, cat: light.cat.slice(0, 4) }, dark: { seq: dark.seq, cat: dark.cat.slice(0, 4) } })) }
    : config;
  const svg = fs.readFileSync(P('src/map/ukraine.svg'), 'utf8').replace(/<!--[\s\S]*?-->\n?/g, '').trim();
  const lang = config.options?.lang || 'uk';
  const title = pick(config.title, lang) || slug;
  const description = pick(config.description, lang) || pick(config.subtitle, lang) || '';

  const values = {
    TITLE: escHtml(title),
    DESCRIPTION: escHtml(description),
    LANG: lang,
    CSS: css,
    SVG: svg,
    CONFIG: jsonForScript(pageConfig),
    DATA: jsonForScript(data),
    REGIONS: jsonForScript(regions),
    JS: js,
  };
  let html = fs.readFileSync(P('src/template/index.html'), 'utf8').replace(/\{\{([A-Z]+)\}\}/g, (m, k) => (k in values ? values[k] : m));
  if (dev) {
    // The Artifact host wraps the published page in a standards-mode skeleton; mimic it for local preview.
    html = `<!doctype html>\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n<style>:root{padding:env(safe-area-inset-top,0px) 0 env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui,sans-serif}[hidden]{display:none!important}</style>\n${html}`;
    html += `\n<script>(()=>{let v=null;setInterval(async()=>{try{const r=await fetch('/__build');const t=await r.text();if(v&&t!==v)location.reload();v=t}catch{}},700)})()</script>\n`;
  }

  // dev builds (doctype + live reload) go to dist/dev/ so they can never be published by mistake
  const outDir = dev ? P('dist', 'dev') : P('dist');
  fs.mkdirSync(outDir, { recursive: true });
  const out = path.join(outDir, `${slug}.html`);
  fs.writeFileSync(out, html);
  const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
  console.log(`✓ ${slug}: ${path.relative(ROOT, out).replace(/\\/g, '/')} (${kb} KB) · ${prepared.periods.length} period(s) · layers: ${layerTypes.join(', ')} · panels: ${panelTypes.join(', ') || '—'}`);
  for (const w of warnings) console.warn(`  ! ${w}`);
  return out;
}

async function main() {
  const slugs = flag('--all')
    ? fs.readdirSync(P('artefacts')).filter((d) => !d.startsWith('_') && fs.existsSync(P('artefacts', d, 'artefact.json')))
    : args.filter((a) => !a.startsWith('--') && a !== opt('--port'));
  if (!slugs.length) {
    console.error('Usage: node tools/build.mjs <slug> [--watch] [--serve] [--port 5173] | --all');
    process.exit(1);
  }
  const dev = flag('--watch') || flag('--serve');
  let buildId = 0;
  const runAll = async () => {
    for (const s of slugs) {
      try {
        await build(s, { dev });
      } catch (e) {
        console.error(`✗ ${s}: ${e.message}`);
        if (!dev) process.exitCode = 1;
      }
    }
    buildId++;
  };
  await runAll();

  if (flag('--watch')) {
    let t = 0;
    const trigger = () => {
      clearTimeout(t);
      t = setTimeout(runAll, 120);
    };
    fs.watch(P('src'), { recursive: true }, trigger);
    for (const s of slugs) fs.watch(P('artefacts', s), { recursive: true }, trigger);
    console.log('watching src/ and artefacts/ …');
  }
  if (flag('--serve')) {
    const port = +opt('--port', 5173);
    http
      .createServer((req, res) => {
        const url = decodeURIComponent(req.url.split('?')[0]);
        if (url === '/__build') return res.end(String(buildId));
        if (url === '/') {
          res.writeHead(302, { Location: `/${slugs[0]}.html` });
          return res.end();
        }
        const file = path.join(P('dist', 'dev'), path.normalize(url).replace(/^([/\\])+/, ''));
        if (!file.startsWith(P('dist', 'dev')) || !fs.existsSync(file)) {
          res.writeHead(404);
          return res.end('not found');
        }
        res.writeHead(200, { 'Content-Type': file.endsWith('.html') ? 'text/html; charset=utf-8' : 'application/octet-stream', 'Cache-Control': 'no-store' });
        fs.createReadStream(file).pipe(res);
      })
      .listen(port, () => console.log(`serving http://localhost:${port}/${slugs[0]}.html`));
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
