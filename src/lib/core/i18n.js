/** Picks the right language from a {uk, en} object (plain strings are returned as-is). */
export function pick(v, lang) {
  if (v == null) return '';
  if (typeof v !== 'object') return String(v);
  return v[lang] ?? v.uk ?? v.en ?? Object.values(v)[0] ?? '';
}
